# -------------------------------------------------------------------- build

def build():
    if THEME.exists():
        shutil.rmtree(THEME)
    (THEME / "assets" / "css").mkdir(parents=True)
    (THEME / "assets" / "js").mkdir(parents=True)

    # Logos and photos
    shutil.copytree(SITE / "assets" / "img", THEME / "assets" / "img")
    for f in (SITE / "assets").glob("*.png"):
        shutil.copy(f, THEME / "assets" / f.name)

    # --- Stylesheet: style.css sits at the theme root, one level above the static one.
    css = (SITE / "assets" / "css" / "style.css").read_text(encoding="utf-8")
    css = must_replace(css, 'url("../img/', 'url("assets/img/')
    (THEME / "style.css").write_text(STYLE_HEADER + "\n" + css + EXTRA_CSS, encoding="utf-8")

    # --- Script: the quote form posts to WordPress instead of the Firebase function.
    js = (SITE / "assets" / "js" / "main.js").read_text(encoding="utf-8")
    js = must_replace(js, "  document.getElementById('year').textContent = new Date().getFullYear();\n\n", "")
    js = must_replace(
        js,
        """    var data = {};
    new FormData(form).forEach(function (value, key) { data[key] = value; });
    return fetch('/api/quote', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(data)
    }).then(function (res) { if (!res.ok) throw new Error('send failed'); });
""",
        """    var data = new FormData(form);
    data.append('action', 'sonic_quote');
    return fetch(sonicQuote.ajaxUrl, { method: 'POST', body: data, credentials: 'same-origin' })
      .then(function (res) { return res.json(); })
      .then(function (res) { if (!res || !res.success) throw new Error('send failed'); });
""",
    )
    (THEME / "assets" / "js" / "main.js").write_text(js, encoding="utf-8")

    # --- Pages
    descriptions = {}
    footer = None
    for source, (slug, title) in PAGES.items():
        html = (SITE / source).read_text(encoding="utf-8")
        desc = between(html, '<meta name="description" content="', '">')

        if source == "dashboard.html":
            descriptions[slug] = desc
            (THEME / "assets" / "css" / "dashboard.css").write_text(between(html, "<style>\n", "</style>"), encoding="utf-8")
            (THEME / "assets" / "js" / "dashboard.js").write_text(
                between(html, "<script>\n", "</script>", last=True), encoding="utf-8"
            )
            body = between(html, "<body>\n", "<script>").strip()
            (THEME / f"page-{slug}.php").write_text(DASHBOARD_PHP.replace("__BODY__", wp_links(body)), encoding="utf-8")
            continue

        body = between(html, "<body>\n", '<footer class="footer">')
        if footer is None:
            footer = '<footer class="footer">' + between(html, '<footer class="footer">', "</footer>") + "</footer>"

        template = (
            PAGE_PHP.replace("__TITLE__", title)
            .replace("__SOURCE__", source)
            .replace("__BODY__", wp_links(body).strip() + "\n")
        )
        if slug is None:
            home_desc = desc
            (THEME / "front-page.php").write_text(template, encoding="utf-8")
        else:
            descriptions[slug] = desc
            (THEME / f"page-{slug}.php").write_text(template, encoding="utf-8")

    footer = wp_links(footer)
    footer = must_replace(footer, '<span id="year">2026</span>', "<span id=\"year\"><?php echo esc_html( gmdate( 'Y' ) ); ?></span>")
    (THEME / "footer.php").write_text(FOOTER_PHP.replace("__FOOTER__", footer), encoding="utf-8")

    # --- Shared files
    pages_php = "\n".join(
        "\t\t'%s' => '%s'," % (slug, php_str(title)) for slug, title in PAGES.values() if slug
    )
    desc_php = "\n".join("\t\t'%s' => '%s'," % (slug, php_str(text)) for slug, text in descriptions.items())
    functions = (
        FUNCTIONS_PHP.replace("__VERSION__", VERSION)
        .replace("__FONTS_URL__", FONTS_URL)
        .replace("__PAGES__", pages_php)
        .replace("__DESCRIPTIONS__", desc_php)
        .replace("__HOME_DESCRIPTION__", php_str(home_desc))
    )
    (THEME / "functions.php").write_text(functions, encoding="utf-8")
    (THEME / "header.php").write_text(HEADER_PHP, encoding="utf-8")
    (THEME / "index.php").write_text(INDEX_PHP, encoding="utf-8")
    (THEME / "readme.txt").write_text(README_TXT, encoding="utf-8")

    # Theme thumbnail for the WordPress admin (macOS only; skipped elsewhere).
    shot = THEME / "screenshot.png"
    try:
        subprocess.run(
            ["sips", "-s", "format", "png", "--resampleHeight", "900", "-c", "900", "1200",
             str(SITE / "assets" / "img" / "hero-warehouse.jpg"), "--out", str(shot)],
            check=True, capture_output=True,
        )
    except (OSError, subprocess.CalledProcessError):
        print("Skipped screenshot.png (sips not available)")

    # --- Zip
    zip_path = OUT / "sonic-fulfillment.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(THEME.rglob("*")):
            if f.is_file() and f.name != ".DS_Store":
                z.write(f, f.relative_to(OUT))

    print(f"Theme folder: {THEME}")
    print(f"Upload file:  {zip_path} ({zip_path.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    build()
