def between(text, start, end, last=False):
    """Return the text between two markers (exclusive)."""
    i = text.rindex(start) if last else text.index(start)
    i += len(start)
    return text[i:text.index(end, i)]


def must_replace(text, old, new):
    if old not in text:
        raise SystemExit(f"Expected to find this in the source, but didn't:\n{old}")
    return text.replace(old, new)


def php_str(text):
    return text.replace("\\", "\\\\").replace("'", "\\'")


def wp_links(html):
    """Point asset and page links at WordPress."""
    html = re.sub(
        r'src="(assets/[^"]+)"',
        lambda m: "src=\"<?php echo esc_url( get_theme_file_uri( '%s' ) ); ?>\"" % m.group(1),
        html,
    )

    def page_link(m):
        slug = PAGES[m.group(1)][0]
        frag = m.group(2) or ""
        if slug is None:
            return "href=\"<?php echo esc_url( home_url( '/%s' ) ); ?>\"" % frag
        if frag:
            return "href=\"<?php echo esc_url( sonic_page_url( '%s' ) . '%s' ); ?>\"" % (slug, frag)
        return "href=\"<?php echo esc_url( sonic_page_url( '%s' ) ); ?>\"" % slug

    names = "|".join(re.escape(n) for n in PAGES)
    return re.sub(r'href="(%s)(#[\w-]+)?"' % names, page_link, html)


